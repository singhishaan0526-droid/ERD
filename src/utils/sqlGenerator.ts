import { Entity, Relationship, Attribute, AttributeType, Cardinality } from '../types';

export type SqlDialect = 'standard' | 'postgres' | 'mysql' | 'sqlite';

export interface SqlGeneratorOptions {
  dialect?: SqlDialect;
  includeDropTable?: boolean;
  includeComments?: boolean;
}

/**
 * Generate standard, production-ready SQL DDL from an Entity-Relationship (ER) model
 */
export function generateSqlFromERModel(
  entities: Entity[],
  relationships: Relationship[],
  options: SqlGeneratorOptions = {}
): string {
  const dialect = options.dialect || 'standard';
  const includeDropTable = options.includeDropTable ?? false;
  const includeComments = options.includeComments ?? true;

  if (!entities || entities.length === 0) {
    return '-- ER Diagram is currently empty.\n-- Add entities and relationships to generate SQL DDL.';
  }

  const lines: string[] = [];

  if (includeComments) {
    lines.push('-- ========================================================');
    lines.push('-- Generated by ER Diagram Maker');
    lines.push(`-- Dialect: ${dialect.toUpperCase()}`);
    lines.push(`-- Total Entities: ${entities.length}`);
    lines.push(`-- Total Relationships: ${relationships.length}`);
    lines.push('-- Generated at: ' + new Date().toISOString());
    lines.push('-- ========================================================\n');
  }

  // Create an entity lookup map
  const entityMap = new Map<string, Entity>();
  entities.forEach(e => entityMap.set(e.id, e));

  // Determine foreign keys to add to entities based on relationships:
  // For 1:N: fromEntity (1) -> toEntity (N), so toEntity gets the FK pointing to fromEntity.
  // For 1:1: toEntity gets the FK with a UNIQUE constraint.
  // For M:N: Creates a junction/associative table.
  const entityFks = new Map<string, Array<{
    colName: string;
    dataType: string;
    targetTable: string;
    targetPk: string;
    isUnique: boolean;
  }>>();

  const junctionTables: Array<{
    name: string;
    table1: string;
    pk1: string;
    fk1Col: string;
    table2: string;
    pk2: string;
    fk2Col: string;
  }> = [];

  relationships.forEach(rel => {
    const fromEnt = entityMap.get(rel.fromEntityId);
    const toEnt = entityMap.get(rel.toEntityId);
    if (!fromEnt || !toEnt) return;

    const fromPk = fromEnt.attributes.find(a => a.isPrimaryKey) || fromEnt.attributes[0];
    const toPk = toEnt.attributes.find(a => a.isPrimaryKey) || toEnt.attributes[0];

    const fromPkName = fromPk ? fromPk.name : `${fromEnt.name}ID`;
    const toPkName = toPk ? toPk.name : `${toEnt.name}ID`;

    if (rel.cardinality === 'M:N') {
      // Junction table
      junctionTables.push({
        name: `${formatTableName(fromEnt.name)}_${formatTableName(toEnt.name)}`,
        table1: formatTableName(fromEnt.name),
        pk1: fromPkName,
        fk1Col: `${formatColumnName(fromEnt.name)}_id`,
        table2: formatTableName(toEnt.name),
        pk2: toPkName,
        fk2Col: `${formatColumnName(toEnt.name)}_id`
      });
    } else if (rel.cardinality === '1:1') {
      // 1:1: toEnt gets FK with UNIQUE constraint
      const list = entityFks.get(toEnt.id) || [];
      list.push({
        colName: `${formatColumnName(fromEnt.name)}_id`,
        dataType: inferSqlType(fromPkName, dialect),
        targetTable: formatTableName(fromEnt.name),
        targetPk: fromPkName,
        isUnique: true
      });
      entityFks.set(toEnt.id, list);
    } else {
      // 1:N or N:1:
      // In Chen convention: fromEntity (1) -> toEntity (N)
      const targetEntity = rel.cardinality === 'N:1' ? fromEnt : toEnt;
      const sourceEntity = rel.cardinality === 'N:1' ? toEnt : fromEnt;
      const sourcePkName = rel.cardinality === 'N:1' ? toPkName : fromPkName;

      const list = entityFks.get(targetEntity.id) || [];
      list.push({
        colName: `${formatColumnName(sourceEntity.name)}_id`,
        dataType: inferSqlType(sourcePkName, dialect),
        targetTable: formatTableName(sourceEntity.name),
        targetPk: sourcePkName,
        isUnique: false
      });
      entityFks.set(targetEntity.id, list);
    }
  });

  // Optional DROP TABLE statements in reverse dependency order
  if (includeDropTable) {
    junctionTables.forEach(jt => {
      lines.push(`DROP TABLE IF EXISTS ${quoteIdentifier(jt.name, dialect)};`);
    });
    // Drop child tables before parent tables
    [...entities].reverse().forEach(ent => {
      lines.push(`DROP TABLE IF EXISTS ${quoteIdentifier(formatTableName(ent.name), dialect)};`);
    });
    lines.push('');
  }

  // Generate CREATE TABLE for each Entity
  entities.forEach(ent => {
    const tableName = formatTableName(ent.name);
    const tableFks = entityFks.get(ent.id) || [];

    lines.push(`-- Table: ${tableName}${ent.isWeak ? ' (Weak Entity)' : ''}`);
    lines.push(`CREATE TABLE ${quoteIdentifier(tableName, dialect)} (`);

    const columnDefs: string[] = [];
    const pkColumns: string[] = [];
    const tableConstraints: string[] = [];

    // Filter out derived attributes as they are computed (e.g. TotalAmount, Age)
    const storedAttributes = ent.attributes.filter(a => a.attributeType !== 'derived');

    // Add regular attributes
    storedAttributes.forEach(attr => {
      const colName = formatColumnName(attr.name);
      const isPk = attr.isPrimaryKey || attr.attributeType === 'primary' || attr.attributeType === 'partial';

      if (isPk) {
        pkColumns.push(quoteIdentifier(colName, dialect));
      }

      let typeStr = inferSqlType(attr.name, dialect, isPk);
      let colDef = `  ${quoteIdentifier(colName, dialect)} ${typeStr}`;

      if (isPk) {
        colDef += ' NOT NULL';
      }

      columnDefs.push(colDef);
    });

    // Add Foreign Key columns
    tableFks.forEach(fk => {
      // Ensure column name doesn't collide
      let fkColName = fk.colName;
      if (storedAttributes.some(a => formatColumnName(a.name).toLowerCase() === fkColName.toLowerCase())) {
        fkColName = `fk_${fkColName}`;
      }

      let colDef = `  ${quoteIdentifier(fkColName, dialect)} ${fk.dataType} NOT NULL`;
      if (fk.isUnique) {
        colDef += ' UNIQUE';
      }
      columnDefs.push(colDef);

      tableConstraints.push(
        `  CONSTRAINT ${quoteIdentifier(`fk_${tableName}_${fk.targetTable}`, dialect)} FOREIGN KEY (${quoteIdentifier(fkColName, dialect)}) REFERENCES ${quoteIdentifier(fk.targetTable, dialect)} (${quoteIdentifier(fk.targetPk, dialect)}) ON DELETE CASCADE`
      );
    });

    // Add Primary Key constraint
    if (pkColumns.length > 0) {
      columnDefs.push(`  PRIMARY KEY (${pkColumns.join(', ')})`);
    }

    // Combine column definitions & constraints
    const allBodyElements = [...columnDefs, ...tableConstraints];
    lines.push(allBodyElements.join(',\n'));
    lines.push(');\n');
  });

  // Generate Junction Tables for M:N relationships
  if (junctionTables.length > 0) {
    lines.push('-- ========================================================');
    lines.push('-- Many-to-Many (M:N) Relationship Junction Tables');
    lines.push('-- ========================================================\n');

    junctionTables.forEach(jt => {
      lines.push(`-- Junction Table for ${jt.table1} <-> ${jt.table2}`);
      lines.push(`CREATE TABLE ${quoteIdentifier(jt.name, dialect)} (`);
      lines.push(`  ${quoteIdentifier(jt.fk1Col, dialect)} ${inferSqlType(jt.pk1, dialect)} NOT NULL,`);
      lines.push(`  ${quoteIdentifier(jt.fk2Col, dialect)} ${inferSqlType(jt.pk2, dialect)} NOT NULL,`);
      lines.push(`  PRIMARY KEY (${quoteIdentifier(jt.fk1Col, dialect)}, ${quoteIdentifier(jt.fk2Col, dialect)}),`);
      lines.push(`  FOREIGN KEY (${quoteIdentifier(jt.fk1Col, dialect)}) REFERENCES ${quoteIdentifier(jt.table1, dialect)} (${quoteIdentifier(jt.pk1, dialect)}) ON DELETE CASCADE,`);
      lines.push(`  FOREIGN KEY (${quoteIdentifier(jt.fk2Col, dialect)}) REFERENCES ${quoteIdentifier(jt.table2, dialect)} (${quoteIdentifier(jt.pk2, dialect)}) ON DELETE CASCADE`);
      lines.push(');\n');
    });
  }

  return lines.join('\n');
}

/**
 * Intelligent SQL data type inference based on attribute name conventions and academic DBMS standards
 */
function inferSqlType(name: string, dialect: SqlDialect, isPk: boolean = false): string {
  const lower = name.toLowerCase();

  if (isPk) {
    if (dialect === 'postgres') return 'SERIAL';
    if (dialect === 'sqlite') return 'INTEGER';
    if (dialect === 'mysql') return 'INT AUTO_INCREMENT';
    return 'INT';
  }

  // Integer IDs
  if (lower.endsWith('id') || lower.endsWith('_id') || lower === 'id') {
    return 'INT';
  }

  // Numbers & Quantities
  if (lower.includes('count') || lower.includes('quantity') || lower.includes('number') || lower.includes('copies') || lower.includes('year') || lower.includes('semester')) {
    return 'INT';
  }

  // Currency & Decimals
  if (lower.includes('price') || lower.includes('amount') || lower.includes('salary') || lower.includes('budget') || lower.includes('cost') || lower.includes('fee') || lower.includes('rate') || lower.includes('gpa')) {
    return 'DECIMAL(10, 2)';
  }

  // Dates & Timestamps
  if (lower.endsWith('date') || lower.includes('dob') || lower === 'birthdate') {
    return 'DATE';
  }
  if (lower.endsWith('time') || lower.endsWith('at') || lower.includes('timestamp')) {
    return dialect === 'postgres' ? 'TIMESTAMP WITH TIME ZONE' : 'TIMESTAMP';
  }

  // Boolean flags
  if (lower.startsWith('is_') || lower.startsWith('has_') || lower === 'active' || lower.includes('status') && lower.length < 8) {
    return dialect === 'postgres' ? 'BOOLEAN' : 'TINYINT(1)';
  }

  // Text & Long descriptions
  if (lower.includes('description') || lower.includes('biography') || lower.includes('content') || lower.includes('notes') || lower.includes('address')) {
    return 'TEXT';
  }

  // Contact / Short strings
  if (lower.includes('email')) {
    return 'VARCHAR(150)';
  }
  if (lower.includes('phone')) {
    return 'VARCHAR(25)';
  }
  if (lower.includes('code') || lower.includes('isbn') || lower.includes('ssn')) {
    return 'VARCHAR(30)';
  }

  // Default string
  return 'VARCHAR(255)';
}

function formatTableName(name: string): string {
  const clean = name.replace(/[^\w]/g, '_').trim();
  return clean.charAt(0).toUpperCase() + clean.slice(1);
}

function formatColumnName(name: string): string {
  return name.replace(/[^\w]/g, '_').trim();
}

function quoteIdentifier(id: string, dialect: SqlDialect): string {
  switch (dialect) {
    case 'postgres':
    case 'standard':
      return `"${id}"`;
    case 'mysql':
      return `\`${id}\``;
    case 'sqlite':
      return `"${id}"`;
    default:
      return id;
  }
}
